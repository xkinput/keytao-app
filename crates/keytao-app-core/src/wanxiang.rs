pub async fn manage_grammar(
    core: &std::sync::Arc<Core>,
    installed: bool,
    host: &impl SchemeHost,
) -> Result<GrammarStatus, CoreError> {
    let result: Result<_, String> = async {
        if installed && !grammar_supported() {
            return Err("当前平台未加载语法模型插件".into());
        }
        let root = host.user_root()?;
        if !status_at(&root).installed {
            return Err("请先安装万象拼音".into());
        }
        let mut receipt = InstallReceipt::new(&root)?;
        let mut cancel = core.download_cancel.subscribe();
        cancel.borrow_and_update();
        core.emit(CoreEvent::InstallProgress(InstallProgress {
            stage: "wanxiang-grammar-download".into(),
            percent: 0,
            message: if installed {
                "正在准备语法模型…"
            } else {
                "正在删除语法模型…"
            }
            .into(),
        }));
        let download = if installed && !safe_target(&root, GRAMMAR_FILE)?.is_file() {
            Some(download_grammar(core, &root, &mut cancel).await?)
        } else {
            None
        };
        if cancel.has_changed().unwrap_or(false) {
            return Err(crate::download::DOWNLOAD_CANCELLED.into());
        }
        core.emit(CoreEvent::InstallProgress(InstallProgress {
            stage: "wanxiang-grammar-deploy".into(),
            percent: 92,
            message: "正在部署万象拼音…".into(),
        }));
        commit_grammar(
            &mut receipt,
            download
                .as_ref()
                .map(|(path, package)| (path.as_ref(), package)),
            installed,
            grammar_supported(),
        )?;
        #[cfg(windows)]
        let mut public_update = None;
        let deployment = async {
            #[cfg(windows)]
            let public_source_warning = {
                match crate::windows_public_schemas::update_public_schemas(
                    || host.publish_wanxiang_sources(&receipt.public_source_files()),
                ) {
                    Ok(update) => {
                        public_update = Some(update);
                        None
                    }
                    Err(error) => Some(crate::windows_public_schemas::public_warning(
                        "wanxiang-grammar-public-sources", &error,
                    )),
                }
            };
            host.deploy().await?;
            #[cfg(windows)]
            if let Some(warning) = public_source_warning {
                core.emit(CoreEvent::DeployProgress(format!("系统搜索框方案未更新：{warning}")));
            }
            if !status_at(&root).deployed {
                return Err("万象拼音部署产物缺失".to_string());
            }
            Ok(())
        }
        .await;
        if let Err(error) = deployment {
            let rollback = receipt.rollback();
            #[cfg(windows)]
            let public_rollback = public_update.map_or(Ok(()), |update| update.rollback());
            rollback.map_err(|restore| format!("{error}；恢复语法模型失败：{restore}"))?;
            #[cfg(windows)]
            public_rollback.map_err(|restore| format!("{error}；恢复公共方案失败：{restore}"))?;
            host.deploy()
                .await
                .map_err(|restore| format!("{error}；已恢复文件，请重新部署：{restore}"))?;
            return Err(error);
        }
        receipt.finish()?;
        core.emit(CoreEvent::InstallProgress(InstallProgress {
            stage: "done".into(),
            percent: 100,
            message: if installed {
                "语法模型已安装"
            } else {
                "语法模型已删除"
            }
            .into(),
        }));
        grammar_status(&root).map_err(|error| error.to_string())
    }
    .await;
    result.map_err(CoreError::Other)
}

pub async fn manage_wanxiang(
    core: &std::sync::Arc<Core>,
    installed: bool,
    variant: String,
    host: &impl SchemeHost,
) -> Result<Status, CoreError> {
    manage_wanxiang_with(core, installed, variant, host, |root, variant| async move {
        let progress_core = core.clone();
        install(&root, &variant, move |percent, message| {
            progress_core.emit(CoreEvent::InstallProgress(InstallProgress {
                stage: "wanxiang-download".into(),
                percent: u32::from(percent),
                message: message.into(),
            }));
        })
        .await
    })
    .await
}

async fn manage_wanxiang_with<Install, InstallFuture>(
    core: &std::sync::Arc<Core>,
    installed: bool,
    variant: String,
    host: &impl SchemeHost,
    install_package: Install,
) -> Result<Status, CoreError>
where
    Install: FnOnce(PathBuf, String) -> InstallFuture,
    InstallFuture: std::future::Future<Output = Result<InstallReceipt, String>>,
{
    let result: Result<_, String> = async {
    variant_source(&variant)?;
    let root = host.user_root()?;
    let mut receipt = if installed {
        install_package(root.clone(), variant).await?
    } else {
        uninstall(&root)?
    };
    #[cfg(target_os = "windows")]
    let mut public_update = None;
    let deploy_result = async {
        write_schema_list_transaction(
            &mut receipt,
            SCHEMA_ID,
            installed,
            &crate::addon::shared_data_dir(core, &root),
        )?;
        #[cfg(target_os = "windows")]
        let public_source_warning = {
            match crate::windows_public_schemas::update_public_schemas(|| {
                if installed {
                    host.publish_wanxiang_sources(&receipt.public_source_files())
                } else {
                    host.remove_public_schema(SCHEMA_ID, &[])
                }
            }) {
                Ok(update) => {
                    public_update = Some(update);
                    None
                }
                Err(error) => Some(crate::windows_public_schemas::public_warning(
                    "wanxiang-public-sources", &error,
                )),
            }
        };
        if installed || keytao_core::schema_install_state(&root).installed {
            host.deploy().await?;
        } else {
            let _ = host.write_reload_stamp(&root)?;
        }
        #[cfg(target_os = "windows")]
        if let Some(warning) = public_source_warning {
            core.emit(CoreEvent::DeployProgress(format!("系统搜索框方案未更新：{warning}")));
        }
        if installed && !status_at(&root).deployed {
            return Err("万象拼音部署产物缺失".to_string());
        }
        Ok(())
    }.await;
    if let Err(error) = deploy_result {
        let rollback = receipt.rollback();
        #[cfg(target_os = "windows")]
        let public_rollback = public_update.map_or(Ok(()), |update| update.rollback());
        #[cfg(target_os = "windows")]
        let error = match &public_rollback {
            Ok(()) => error,
            Err(restore) => format!("{error}；恢复公共方案失败：{restore}"),
        };
        if let Err(rollback_error) = rollback {
            return Err(format!("{error}；恢复词库失败：{rollback_error}"));
        }
        #[cfg(target_os = "windows")]
        public_rollback.map_err(|_| error.clone())?;
        if let Err(restore_error) = host.deploy().await {
            return Err(format!("{error}；已恢复文件，请重新部署：{restore_error}"));
        }
        return Err(error);
    }
    receipt.finish()?;
    if !installed {
        for extension in ["schema.yaml", "table.bin", "prism.bin", "reverse.bin"] {
            let path = root.join("build").join(format!("wanxiang.{extension}"));
            if let Err(error) = std::fs::remove_file(&path) {
                if error.kind() != std::io::ErrorKind::NotFound {
                    tracing::info!(%error, path = %path.display(), "unused Wanxiang build cache remains locked");
                }
            }
        }
    }
    core.emit(CoreEvent::InstallProgress(InstallProgress {
        stage: "done".into(),
        percent: 100,
        message: if installed { "万象拼音已安装并部署" } else { "万象拼音已卸载，保留用户自定义和学习记录" }.into(),
    }));
    Ok(status_at(&root))
    }.await;
    result.map_err(CoreError::Other)
}

pub fn wanxiang_status(_core: &Core, root: &Path) -> Result<Status, CoreError> {
    Ok(status_at(root))
}
